/**
 * Mock data generator for ERD tables.
 * Generates realistic dummy data in SQL INSERT and JSON formats based on column types and names.
 */
import { Entity, Column } from '@/types';

function generateFieldValue(column: Column, rowIndex: number): string | number | boolean {
  const name = column.name.toLowerCase();
  const type = column.type.toLowerCase();

  // Primary key integer
  if (column.is_pk && (type.includes('int') || type.includes('serial'))) {
    return rowIndex + 1;
  }

  // UUID
  if (type.includes('uuid') || name === 'id' || name.endsWith('_id')) {
    if (name.endsWith('_id') && !column.is_pk) {
      return `00000000-0000-4000-8000-${String(rowIndex % 5 + 1).padStart(12, '0')}`;
    }
    return `a0eebc99-9c0b-4ef8-bb6d-${String(rowIndex + 1).padStart(12, '0')}`;
  }

  // Specific semantic names
  if (name.includes('email')) {
    const prefixes = ['alice', 'bob', 'charlie', 'david', 'emma', 'frank', 'grace', 'henry'];
    return `${prefixes[rowIndex % prefixes.length] || 'user'}${rowIndex + 1}@example.com`;
  }

  if (name.includes('phone') || name.includes('mobile')) {
    return `+62812${String(1000000 + rowIndex * 12345).slice(0, 8)}`;
  }

  if (name.includes('name')) {
    const names = ['John Doe', 'Jane Smith', 'Michael Brown', 'Emily Davis', 'Alex Wilson', 'Sarah Taylor'];
    return names[rowIndex % names.length] || `Name ${rowIndex + 1}`;
  }

  if (name.includes('price') || name.includes('amount') || name.includes('total') || name.includes('cost')) {
    return Number((((rowIndex + 1) * 25.5) % 500 + 10).toFixed(2));
  }

  if (name.includes('status')) {
    const statuses = ['active', 'pending', 'completed', 'in_progress', 'archived'];
    return statuses[rowIndex % statuses.length];
  }

  if (name.includes('role')) {
    const roles = ['admin', 'member', 'editor', 'viewer'];
    return roles[rowIndex % roles.length];
  }

  // Boolean
  if (type.includes('bool')) {
    return rowIndex % 2 === 0;
  }

  // Date / Timestamp
  if (type.includes('time') || type.includes('date')) {
    const d = new Date(Date.now() - (rowIndex * 86400000 * 2));
    return d.toISOString();
  }

  // Numbers
  if (type.includes('int') || type.includes('number')) {
    return (rowIndex + 1) * 10;
  }

  // Fallback text
  return `${column.name}_val_${rowIndex + 1}`;
}

export function generateTableMockJSON(entity: Entity, count: number = 10): string {
  const rows: Record<string, any>[] = [];
  for (let i = 0; i < count; i++) {
    const row: Record<string, any> = {};
    for (const col of entity.columns) {
      row[col.name] = generateFieldValue(col, i);
    }
    rows.push(row);
  }
  return JSON.stringify(rows, null, 2);
}

export function generateTableMockSQL(entity: Entity, count: number = 10): string {
  const columns = entity.columns.map(c => c.name);
  if (columns.length === 0) return `-- Table ${entity.name} has no columns`;

  const statements: string[] = [
    `-- Mock data for table: ${entity.name}`,
    `-- Generated by Creatool`,
  ];

  const colList = columns.map(c => `"${c}"`).join(', ');

  for (let i = 0; i < count; i++) {
    const vals = entity.columns.map(col => {
      const v = generateFieldValue(col, i);
      if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`;
      if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
      return String(v);
    });
    statements.push(`INSERT INTO "${entity.name}" (${colList}) VALUES (${vals.join(', ')});`);
  }

  return statements.join('\n');
}
